#!/usr/bin/env bash
# Regenerates the Latch launcher icon everywhere it is used, from one glyph.
#
#   ./tool/gen_launcher_icons.sh
#
# Writes:
#   android/app/src/main/res/drawable/ic_launcher_foreground.xml
#   android/app/src/main/res/drawable/ic_launcher_monochrome.xml
#   android/app/src/main/res/mipmap-*/ic_launcher{,_round}.png   (legacy, API < 26)
#   ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png
#   assets/brand/latch-mark.svg
#   assets/brand/play-icon-512.png
#
# Requires: rsvg-convert (brew install librsvg) and ffmpeg.
#
# Geometry rules (Android adaptive icons):
#   - 108dp canvas, of which only the central 72dp is ever visible.
#   - Everything must stay inside the central 66dp circle (r = 33 from 54,54)
#     so no mask shape — circle, squircle, teardrop — can clip it.
#     The glyph as drawn below reaches r = 30.8 at its worst point.
#   - The legacy/iOS/Play rasters reuse the same coordinates with a 72dp
#     viewBox, which reproduces the launcher's 1.5x zoom exactly.
#
# The glyph occupies x 30..78, y 27.5..80.5 on the 108 canvas: centred, and
# clear of both the 66dp keyline and the 72dp mask on every side.

set -euo pipefail
cd "$(dirname "$0")/.."

command -v rsvg-convert >/dev/null || { echo "rsvg-convert not found (brew install librsvg)" >&2; exit 1; }
command -v ffmpeg       >/dev/null || { echo "ffmpeg not found" >&2; exit 1; }

PAPER="#F5F3EF"
GREEN="#2D6B54"

# --- the glyph, drawn once ------------------------------------------------
SHACKLE='M39,46.5a15,15 0 0 1 30,0'
BODY='M42,46.5H66a12,12 0 0 1 12,12v10a12,12 0 0 1 -12,12H42a12,12 0 0 1 -12,-12v-10a12,12 0 0 1 12,-12z'
KEYHOLE_C='M54,55.5a5,5 0 1 1 0,10a5,5 0 1 1 0,-10z'
KEYHOLE_S='M54,62.5a2.3,2.3 0 0 1 2.3,2.3v6.2a2.3,2.3 0 0 1 -4.6,0v-6.2a2.3,2.3 0 0 1 2.3,-2.3z'
# Same keyhole as one closed outline, for the monochrome mask (a real hole).
KEYHOLE_HOLE='M51.7,64.94A5,5 0 1 1 56.3,64.94V70.5A2.3,2.3 0 0 1 51.7,70.5z'

# --- SVG composition ------------------------------------------------------
# $1 = background markup, $2 = viewBox
glyph_svg() {
  printf '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s">%s' "$2" "$1"
  printf '<path d="%s" fill="none" stroke="%s" stroke-width="8" stroke-linecap="round"/>' "$SHACKLE" "$PAPER"
  printf '<path d="%s" fill="%s"/>' "$BODY" "$PAPER"
  printf '<path d="%s" fill="%s"/>' "$KEYHOLE_C" "$GREEN"
  printf '<path d="%s" fill="%s"/>' "$KEYHOLE_S" "$GREEN"
  printf '</svg>\n'
}

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Adaptive foreground: transparent, drawn straight onto the launcher's background.
glyph_svg '' '0 0 108 108'                       > "$TMP/adaptive.svg"
# Brand tile used in the README: rounded square, same glyph, generous padding.
glyph_svg '<rect x="4" y="4" width="100" height="100" rx="26" fill="#2D6B54"/>' '0 0 108 108' > "$TMP/tile.svg"
# Legacy square / round icons: 72dp window onto the 108dp canvas (1.5x zoom).
glyph_svg '<rect x="18" y="18" width="72" height="72" rx="14.4" fill="#2D6B54"/>' '18 18 72 72' > "$TMP/square.svg"
glyph_svg '<circle cx="54" cy="54" r="36" fill="#2D6B54"/>'                        '18 18 72 72' > "$TMP/round.svg"
# Full bleed: iOS (the OS applies its own mask) and the Play listing icon.
glyph_svg '<rect x="18" y="18" width="72" height="72" fill="#2D6B54"/>'            '18 18 72 72' > "$TMP/full.svg"

# --- Android vector drawables --------------------------------------------
RES=android/app/src/main/res/drawable

cat > "$RES/ic_launcher_foreground.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/gen_launcher_icons.sh. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:pathData="$SHACKLE"
        android:strokeColor="$PAPER"
        android:strokeWidth="8"
        android:strokeLineCap="round" />
    <path
        android:fillColor="$PAPER"
        android:pathData="$BODY" />
    <path
        android:fillColor="$GREEN"
        android:pathData="$KEYHOLE_C" />
    <path
        android:fillColor="$GREEN"
        android:pathData="$KEYHOLE_S" />
</vector>
EOF

cat > "$RES/ic_launcher_monochrome.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/gen_launcher_icons.sh. Edit the script, not this file. -->
<!-- Themed-icon mask: the system tints this, so it is drawn in a single colour
     with the keyhole cut out (evenOdd), not painted over. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:pathData="$SHACKLE"
        android:strokeColor="#FFFFFF"
        android:strokeWidth="8"
        android:strokeLineCap="round" />
    <path
        android:fillColor="#FFFFFF"
        android:fillType="evenOdd"
        android:pathData="$BODY$KEYHOLE_HOLE" />
</vector>
EOF

# --- Android legacy rasters (API < 26) ------------------------------------
for pair in mdpi:48 hdpi:72 xhdpi:96 xxhdpi:144 xxxhdpi:192; do
  dpi="${pair%%:*}"; px="${pair##*:}"
  rsvg-convert -w "$px" -h "$px" "$TMP/square.svg" -o "android/app/src/main/res/mipmap-$dpi/ic_launcher.png"
  rsvg-convert -w "$px" -h "$px" "$TMP/round.svg"  -o "android/app/src/main/res/mipmap-$dpi/ic_launcher_round.png"
done

# --- Brand assets ---------------------------------------------------------
cp "$TMP/tile.svg" assets/brand/latch-mark.svg

# Play listing icon: 512x512, no alpha, full bleed (Play applies its own mask).
rsvg-convert -w 512 -h 512 "$TMP/full.svg" -o "$TMP/play-512.png"
ffmpeg -loglevel error -y -i "$TMP/play-512.png" -pix_fmt rgb24 assets/brand/play-icon-512.png

# --- iOS icons ------------------------------------------------------------
# Sizes come from ios/Runner/Assets.xcassets/AppIcon.appiconset/Contents.json.
# iOS rejects an alpha channel, so every file is flattened to rgb24.
ICONSET=ios/Runner/Assets.xcassets/AppIcon.appiconset
for pair in \
  Icon-App-20x20@1x.png:20    Icon-App-20x20@2x.png:40    Icon-App-20x20@3x.png:60 \
  Icon-App-29x29@1x.png:29    Icon-App-29x29@2x.png:58    Icon-App-29x29@3x.png:87 \
  Icon-App-40x40@1x.png:40    Icon-App-40x40@2x.png:80    Icon-App-40x40@3x.png:120 \
  Icon-App-60x60@2x.png:120   Icon-App-60x60@3x.png:180 \
  Icon-App-76x76@1x.png:76    Icon-App-76x76@2x.png:152 \
  Icon-App-83.5x83.5@2x.png:167 \
  Icon-App-1024x1024@1x.png:1024
do
  name="${pair%%:*}"; px="${pair##*:}"
  rsvg-convert -w "$px" -h "$px" "$TMP/full.svg" -o "$TMP/$name"
  ffmpeg -loglevel error -y -i "$TMP/$name" -pix_fmt rgb24 "$ICONSET/$name"
done

echo "Regenerated launcher icon: 2 vectors, 10 mipmaps, 15 iOS icons, 1 Play icon."
